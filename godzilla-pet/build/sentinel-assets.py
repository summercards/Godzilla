#!/usr/bin/env python3
"""Cut the generated master into disjoint anatomical PNGs. No redraw/resynthesis."""
from pathlib import Path
import json
import numpy as np
from PIL import Image, ImageDraw
base=Path(__file__).resolve().parents[1]/'tv/assets/enemies/army/sentinel'
im=Image.open(base/'source/sentinel.png').convert('RGBA')
w,h=im.size
assert (w,h)==(1024,1536)
# Source-space pivots and cut contours are the only authored rig geometry.
def spec(parent,pivot,polygon):return dict(parent=parent,pivot=pivot,polygon=polygon)
slots={
 'head':spec('torso',[492,288],[[290,0],[630,0],[600,265],[547,293],[456,331],[421,290],[290,288]]),
 'far_arm':spec('torso',[346,391],[[240,335],[370,331],[365,440],[393,509],[352,577],[287,598],[255,528]]),
 'far_forearm':spec('far_arm',[323,561],[[287,548],[356,578],[344,643],[277,718],[265,862],[142,862],[160,705],[231,582]]),
 'arm':spec('torso',[678,346],[[613,276],[738,272],[816,410],[825,512],[788,560],[744,552],[674,490],[635,414]]),
 'forearm':spec('arm',[774,538],[[769,506],[826,511],[905,623],[913,868],[711,868],[728,739],[778,704],[743,631],[738,557]]),
 'far_thigh':spec('root',[420,743],[[389,668],[493,767],[493,881],[409,1009],[355,1000],[296,944],[273,816]]),
 'far_shin':spec('far_thigh',[366,976],[[305,928],[365,966],[409,996],[459,1140],[434,1300],[424,1479],[141,1485],[137,1370],[267,1260],[281,1020]]),
 'thigh':spec('root',[560,734],[[528,652],[595,643],[703,752],[751,896],[731,978],[686,1011],[631,980],[554,909],[507,811]]),
 'shin':spec('thigh',[670,977],[[633,948],[691,974],[739,958],[854,1041],[917,1536],[708,1536],[718,1285],[615,1154],[600,1000]]),
 'far_foot':spec('far_shin',[355,1350],[[0,1340],[520,1340],[520,1536],[0,1536]]),
 'foot':spec('shin',[811,1370],[[520,1370],[1024,1370],[1024,1536],[520,1536]]),
 'torso':spec('root',[508,738],[[0,0],[w,0],[w,h],[0,h]])
}
# Child ownership takes priority at shared contours; remaining opaque pixels belong to torso.
order=['foot','far_foot','head','far_forearm','forearm','far_shin','shin','far_arm','arm','far_thigh','thigh','torso']
owner=np.full((h,w),-1,dtype=np.int16)
for i,name in enumerate(order):
 mask=Image.new('L',(w,h));ImageDraw.Draw(mask).polygon([tuple(p) for p in slots[name]['polygon']],fill=255)
 owner[(np.asarray(mask)>0)&(owner<0)]=i
# Assign narrow outer contours missed by the first anatomical masks to their moving limb.
yy,xx=np.indices((h,w));remaining=owner==order.index('torso')
for name,region in [('far_thigh',(yy>=800)&(yy<1000)&(xx<500)),('thigh',(yy>=800)&(yy<1000)&(xx>=500)),('far_shin',(yy>=1000)&(xx<520)),('shin',(yy>=1000)&(xx>=520)),('far_arm',(yy>=470)&(yy<575)&(xx<385))]:
 owner[remaining&region]=order.index(name)
arr=np.array(im);metadata={ 'scale':.265,'origin':[520,1518],'sourceSize':[w,h],'order':['far_thigh','far_shin','far_foot','far_arm','far_forearm','torso','thigh','shin','foot','head','arm','forearm'],'slots':{},'seams':{} }
reconstructed=np.zeros_like(arr)
for i,name in enumerate(order):
 part=arr.copy();part[owner!=i]=0;reconstructed[owner==i]=part[owner==i]
 img=Image.fromarray(part);bounds=img.getbbox();assert bounds,name
 x,y,x1,y1=bounds
 dest=base/'parts'/name;dest.mkdir(parents=True,exist_ok=True);img.crop(bounds).save(dest/'default.png')
 a=slots[name];metadata['slots'][name]={'parent':a['parent'],'pivot':a['pivot'],'bounds':list(bounds)}
 # Original textured joint cap; only drawn when a joint rotates.
 if name!='torso':
  px,py=a['pivot'];r=46 if 'thigh' in name or name in ['arm','far_arm'] else 34
  m=Image.new('L',(w,h));ImageDraw.Draw(m).ellipse((px-r,py-r,px+r,py+r),fill=255)
  patch=arr.copy();patch[np.asarray(m)==0]=0
  Image.fromarray(patch).crop((px-r,py-r,px+r,py+r)).save(dest/'joint.png')
  metadata['seams'][name]={'radius':r}
assert np.array_equal(reconstructed,arr),'Partition must preserve every source pixel including original alpha'
(base/'source/parts.json').write_text(json.dumps({'cuts':slots,'rig':metadata},indent=2)+'\n')
(base/'rig.data.js').write_text('// Generated by build/sentinel-assets.py; do not edit.\n(function(r){const data='+json.dumps(metadata,separators=(',',':'))+';if(typeof module!=="undefined"&&module.exports)module.exports=data;else r.SentinelRigData=data;})(typeof window!=="undefined"?window:this);\n')
print('12 parts, 11 textured joint caps; bind reconstruction RGBA difference: 0')
